export interface KoleksiSpec {
  id: string;
  name: string;
  kategori: Kategori;
  family: Family;
  /** Varian desain di dalam keluarga (mis. "linen", "catur", "lebaran"). */
  varian: string;
  layout: LayoutKey;
  /** Palet: latar, tinta (teks utama), aksen, warna lembut (slot kosong). */
  bg: string;
  ink: string;
  accent: string;
  soft: string;
  /**
   * Tulisan utama: "merek" = Potretin, teks lain = kata umum,
   * null = tanpa tulisan (hanya tanggal).
   */
  teks: "merek" | string | null;
  /** Font tulisan utama (kunci di scripts/frames/art.ts). */
  font?: string;
  radius: number;
  dateFont: "sans" | "serif" | "mono";
  /** Warna tanggal (bawaan: tinta). */
  dateColor?: string;
  /** Lapisan hiasan di atas foto. */
  front?: boolean;
}

